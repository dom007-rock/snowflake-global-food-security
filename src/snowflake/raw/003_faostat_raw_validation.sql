USE ROLE GFS_PLATFORM_ADMIN;

USE DATABASE GFS_DEV;
USE SCHEMA RAW;


SELECT 'QCL' AS DOMAIN, COUNT(*) AS ROW_COUNT
FROM FAOSTAT_QCL

UNION ALL

SELECT 'LC', COUNT(*)
FROM FAOSTAT_LC

UNION ALL

SELECT 'ESB', COUNT(*)
FROM FAOSTAT_ESB

UNION ALL

SELECT 'FBS', COUNT(*)
FROM FAOSTAT_FBS

UNION ALL

SELECT 'GT', COUNT(*)
FROM FAOSTAT_GT

UNION ALL

SELECT 'FS', COUNT(*)
FROM FAOSTAT_FS

ORDER BY DOMAIN;